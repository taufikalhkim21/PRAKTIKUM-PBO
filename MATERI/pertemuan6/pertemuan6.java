
package pertemuan6;


public class pertemuan6 {
    public static void main(String[] args) {
        int[] angka = {10, 20, 30, 40};
        String buah[] = {"Mangga", "Nanas", "Melon"};
        
        
        for (int a : angka){
            System.out.println(a);
        }
        
        for (int i = 0; i < buah.length; i++) {
            System.out.println("Buah " + buah[i]);
        }
        
    }
}
